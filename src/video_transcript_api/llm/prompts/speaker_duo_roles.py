SPEAKER_DUO_ROLES_INSTRUCTION = """

## 角色判断（roles 字段，必填）

`roles` 给每个说话人标一个角色，取值只能是 `host`、`guest`、`unknown`：

- `host`：主持人——负责提问、引导话题、串场、把话头交给对方的人。
- `guest`：嘉宾——被提问、被访谈的一方。
- `unknown`：分不清时的诚实答案，不要猜。

判断依据只有对话内容本身：谁在提问和引导、谁在被访谈。**发布账号（作者）
不一定是主持人**——作者可能只是发布这条内容的人，主持人往往是对话里的另一
方；标题里出现的人名通常是被访谈的嘉宾，但也可能不是。

只对主要发言方判断角色；听众、路人、短暂插话者一律填 `unknown`。分不清两人
谁是主持人谁是嘉宾时，把两人都填 `unknown`——程序会因此放弃推测显示名，这比
标错角色安全。
"""
